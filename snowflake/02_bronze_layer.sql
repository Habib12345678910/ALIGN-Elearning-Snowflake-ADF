-- 1. Set the Snowflake execution context

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE TECHINNOV_DB;
USE SCHEMA PUBLIC;

-- 2. Inspect imported source tables

SHOW TABLES IN SCHEMA TECHINNOV_DB.PUBLIC;

-- 3. Preview the dimension tables

SELECT * FROM PUBLIC.DIM_CONCEPT LIMIT 10;

SELECT * FROM PUBLIC.DIM_CONTENT_TYPE LIMIT 10;

SELECT * FROM PUBLIC.DIM_DATE LIMIT 10;

SELECT * FROM PUBLIC.DIM_MODULE LIMIT 10;

SELECT * FROM PUBLIC.DIM_QUESTION LIMIT 10;

SELECT * FROM PUBLIC.DIM_USER LIMIT 10;

-- 4. Preview the fact table

SELECT *
FROM PUBLIC.FACT_LEARNINGATTEMPT
LIMIT 10;

-- 5. Inspect the source table structure

DESCRIBE TABLE PUBLIC.FACT_LEARNINGATTEMPT;

-- 6. Validate the initial data volume

SELECT COUNT(*) AS TOTAL_SOURCE_ATTEMPTS
FROM PUBLIC.FACT_LEARNINGATTEMPT;

-- 7. Source data reconciliation

SELECT 'DIM_USER' AS TABLE_NAME,
       COUNT(*) AS ROW_COUNT
FROM PUBLIC.DIM_USER

UNION ALL

SELECT 'DIM_MODULE', COUNT(*)
FROM PUBLIC.DIM_MODULE

UNION ALL

SELECT 'DIM_DATE', COUNT(*)
FROM PUBLIC.DIM_DATE

UNION ALL

SELECT 'DIM_CONCEPT', COUNT(*)
FROM PUBLIC.DIM_CONCEPT

UNION ALL

SELECT 'DIM_CONTENT_TYPE', COUNT(*)
FROM PUBLIC.DIM_CONTENT_TYPE

UNION ALL

SELECT 'DIM_QUESTION', COUNT(*)
FROM PUBLIC.DIM_QUESTION

UNION ALL

SELECT 'FACT_LEARNINGATTEMPT', COUNT(*)
FROM PUBLIC.FACT_LEARNINGATTEMPT;

