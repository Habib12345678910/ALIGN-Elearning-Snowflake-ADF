-- 1. Set the execution context

USE WAREHOUSE COMPUTE_WH;
USE DATABASE TECHINNOV_DB;

-- 2. Create the Silver schema

CREATE SCHEMA IF NOT EXISTS TECHINNOV_DB.SILVER;

-- 3. Create and populate dimension tables

CREATE TABLE IF NOT EXISTS SILVER.DIM_USER AS
SELECT * FROM PUBLIC.DIM_USER;

CREATE TABLE IF NOT EXISTS SILVER.DIM_MODULE AS
SELECT * FROM PUBLIC.DIM_MODULE;

CREATE TABLE IF NOT EXISTS SILVER.DIM_DATE AS
SELECT * FROM PUBLIC.DIM_DATE;

CREATE TABLE IF NOT EXISTS SILVER.DIM_CONCEPT AS
SELECT * FROM PUBLIC.DIM_CONCEPT;

CREATE TABLE IF NOT EXISTS SILVER.DIM_CONTENT_TYPE AS
SELECT * FROM PUBLIC.DIM_CONTENT_TYPE;

CREATE TABLE IF NOT EXISTS SILVER.DIM_QUESTION AS
SELECT * FROM PUBLIC.DIM_QUESTION;

-- 4. Clean and transform the fact table
-- Apply business rules to validate learning scores
-- Calculate learner score improvement

CREATE TABLE IF NOT EXISTS SILVER.FACT_LEARNINGATTEMPT AS

SELECT *,
    FINALSCORE - INITIALSCORE AS SCORE_IMPROVEMENT

FROM PUBLIC.FACT_LEARNINGATTEMPT

WHERE INITIALSCORE BETWEEN 0 AND 100
  AND FINALSCORE BETWEEN 0 AND 100
  AND ATTEMPTNUMBER >= 1;

-- 5. Verify Silver tables

SHOW TABLES IN SCHEMA TECHINNOV_DB.SILVER;

-- 6. Preview transformed data

SELECT *
FROM SILVER.FACT_LEARNINGATTEMPT
LIMIT 10;

-- 7. Validate the number of transformed records

SELECT COUNT(*) AS TOTAL_SILVER_ATTEMPTS
FROM SILVER.FACT_LEARNINGATTEMPT;

-- 8. Compare Bronze and Silver volumes

SELECT
    'BRONZE' AS DATA_LAYER,
    COUNT(*) AS ROW_COUNT
FROM PUBLIC.FACT_LEARNINGATTEMPT

UNION ALL

SELECT
    'SILVER' AS DATA_LAYER,
    COUNT(*) AS ROW_COUNT
FROM SILVER.FACT_LEARNINGATTEMPT;

-- 9. Validate calculated score improvement

SELECT
    ATTEMPTID,
    INITIALSCORE,
    FINALSCORE,
    SCORE_IMPROVEMENT

FROM SILVER.FACT_LEARNINGATTEMPT
LIMIT 20;

